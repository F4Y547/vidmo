function codeBlock(text) {
  return `\`\`\`\n${String(text ?? '').trim()}\n\`\`\``;
}

function slug(value) {
  return String(value ?? 'project')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 64);
}

export function projectExportName(project) {
  return `${slug(project.dish?.name)}-${project.audience}-miniature-film`;
}

export function buildMarkdown(project) {
  const storyboard = project.storyboard;
  if (!storyboard) throw new Error('Project has no storyboard yet');
  const dish = project.dish;
  const lines = [];
  lines.push(`# ${dish.name} — Miniature Cooking Production Package`);
  lines.push('');
  lines.push(`**Audience:** ${storyboard.audience}`);
  lines.push(`**Dish:** ${dish.name}`);
  lines.push(`**Total Stages:** ${storyboard.totalStages}`);
  lines.push(`**Runtime:** ${storyboard.totalDuration}s`);
  lines.push(`**Aspect:** ${storyboard.aspect}`);
  lines.push(`**Complexity:** ${storyboard.complexityLabel}`);
  lines.push(`**Scale:** ${storyboard.summary.scale}`);
  lines.push(`**Hands:** ${storyboard.summary.hands}`);
  lines.push(`**Environment:** ${storyboard.summary.environment}`);
  lines.push(`**Audio policy:** ${storyboard.summary.audio}`);
  lines.push('');
  lines.push('> Generated by VidMo Studio. Treat every prompt as a locked continuity document.');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Continuity Bible');
  lines.push('');
  for (const [key, value] of Object.entries(storyboard.continuity)) {
    if (key === 'title') continue;
    lines.push(`- **${key.replace(/(^\w|_\w)/g, (match) => ` ${match.replace('_', ' ')}`).trim()}:** ${value}`);
  }
  lines.push('');
  lines.push('## Global Negative Prompt');
  lines.push('');
  lines.push(codeBlock(storyboard.negativePrompt));
  lines.push('');
  lines.push('## Storyboard');
  lines.push('');

  for (const [index, stage] of storyboard.stages.entries()) {
    lines.push(`### STAGE ${index + 1} — ${stage.name}`);
    lines.push('');
    lines.push(
      `**Shot ID:** ${stage.id} · **Duration:** ${stage.duration}s · **Camera:** ${stage.camera} · **Compliance:** ${stage.compliance?.score ?? 100}%`,
    );
    lines.push('');
    lines.push('#### IMAGE PROMPT');
    lines.push('');
    lines.push(codeBlock(stage.imagePrompt));
    lines.push('');
    lines.push('#### MOTION PROMPT');
    lines.push('');
    lines.push(codeBlock(stage.motionPrompt));
    lines.push('');
    lines.push('#### AUDIO PROMPT');
    lines.push('');
    lines.push(codeBlock(stage.audioPrompt));
    lines.push('');
    lines.push('#### NEGATIVE PROMPT');
    lines.push('');
    lines.push(codeBlock(stage.negativePrompt));
    lines.push('');
    lines.push('---');
    lines.push('');
  }

  lines.push('## Thumbnail / Cover Prompt');
  lines.push('');
  lines.push(codeBlock(storyboard.thumbnailPrompt));
  lines.push('');
  lines.push('## Social Copy');
  lines.push('');
  lines.push(`**Hook:** ${storyboard.social.hooks[0]}`);
  lines.push('');
  lines.push(`**Caption:** ${storyboard.social.caption}`);
  lines.push('');
  lines.push('**Titles:**');
  for (const title of storyboard.social.titles) lines.push(`- ${title}`);
  lines.push('');
  lines.push(`**Hashtags:** ${storyboard.social.hashtags}`);
  lines.push('');
  lines.push('## Production Handoff');
  lines.push('');
  for (const model of storyboard.production.videoModels) {
    lines.push(`- **${model.name}** — ${model.mode}, ${model.clip}. ${model.note}`);
  }
  lines.push('');
  lines.push('### Workflow');
  for (const step of storyboard.production.workflow) lines.push(`1. ${step}`);
  lines.push('');
  lines.push('### Final QA');
  for (const check of storyboard.audit.checks) {
    lines.push(`- ${check.pass ? '✅' : '❌'} ${check.label}`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('Generated by VidMo Studio · miniature cooking production automation');
  lines.push('');
  return lines.join('\n');
}

function csvEscape(value) {
  const text = String(value ?? '');
  return `"${text.replace(/"/g, '""')}"`;
}

export function buildShotListCsv(project) {
  const storyboard = project.storyboard;
  if (!storyboard) throw new Error('Project has no storyboard yet');
  const header = [
    'stage',
    'shot_id',
    'name',
    'duration_seconds',
    'camera',
    'action',
    'ingredients',
    'image_prompt',
    'motion_prompt',
    'audio_prompt',
    'negative_prompt',
    'compliance_score',
  ];
  const rows = storyboard.stages.map((stage, index) => [
    index + 1,
    stage.id,
    stage.name,
    stage.duration,
    stage.camera,
    stage.motion,
    stage.ingredients,
    stage.imagePrompt,
    stage.motionPrompt,
    stage.audioPrompt,
    stage.negativePrompt,
    stage.compliance?.score ?? 100,
  ]);
  return `\uFEFF${[header, ...rows].map((row) => row.map(csvEscape).join(',')).join('\r\n')}\r\n`;
}

export function buildProjectJson(project) {
  return JSON.stringify(
    {
      schema: 'vidmo.production-package/v1',
      generatedAt: new Date().toISOString(),
      project: {
        id: project.id,
        title: project.title,
        audience: project.audience,
        dish: project.dish,
        analysis: project.analysis,
        createdAt: project.createdAt,
        updatedAt: project.updatedAt,
      },
      storyboard: project.storyboard,
    },
    null,
    2,
  );
}

export function buildRenderHandoff(project) {
  const storyboard = project.storyboard;
  if (!storyboard) throw new Error('Project has no storyboard yet');
  return {
    schema: 'vidmo.render-handoff/v1',
    generatedAt: new Date().toISOString(),
    projectId: project.id,
    title: project.title,
    audience: project.audience,
    dish: project.dish.name,
    complexity: project.dish.complexity,
    aspect: storyboard.aspect,
    fps: 24,
    masterResolution: '1080x1920',
    audioPolicy: {
      type: 'asmr-only',
      music: false,
      voiceover: false,
      dialogue: false,
      humanSpeech: false,
      instructions:
        'Use ONLY realistic ASMR sound effects. No music, no background music, no songs, no voiceover, no dialogue, no human speech.',
    },
    continuity: storyboard.continuity,
    negativePrompt: storyboard.negativePrompt,
    thumbnailPrompt: storyboard.thumbnailPrompt,
    stages: storyboard.stages.map((stage, index) => ({
      stageId: stage.id,
      index: index + 1,
      name: stage.name,
      duration: stage.duration,
      camera: stage.camera,
      firstFrameImage: `${stage.id.toLowerCase()}-image.png`,
      outputVideo: `${stage.id.toLowerCase()}-motion.mp4`,
      imageJob: {
        prompt: stage.imagePrompt,
        negativePrompt: stage.negativePrompt,
        aspectRatio: '9:16',
        recommendedModels: storyboard.production.imageModels,
      },
      videoJob: {
        prompt: stage.motionPrompt,
        audioPrompt: stage.audioPrompt,
        firstFrame: `${stage.id.toLowerCase()}-image.png`,
        duration: stage.duration,
        aspectRatio: '9:16',
        fps: 24,
      },
      continuity: {
        environment: storyboard.summary.environment,
        hands: storyboard.summary.hands,
        scale: storyboard.summary.scale,
        palette: storyboard.summary.palette,
      },
      compliance: stage.compliance,
    })),
    social: storyboard.social,
    production: storyboard.production,
  };
}

export function buildContinuityMarkdown(project) {
  const storyboard = project.storyboard;
  const lines = [`# Continuity Bible — ${project.dish.name}`, ''];
  for (const [key, value] of Object.entries(storyboard.continuity)) {
    if (key === 'title') continue;
    lines.push(`## ${key.replace(/(^\w|_\w)/g, (match) => ` ${match.replace('_', ' ')}`).trim()}`);
    lines.push('');
    lines.push(String(value));
    lines.push('');
  }
  lines.push('## Global Negative Prompt');
  lines.push('');
  lines.push(storyboard.negativePrompt);
  lines.push('');
  return lines.join('\n');
}

